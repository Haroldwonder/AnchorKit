#!/usr/bin/env bash
#
# Regenerates docs/performance.md with a gas/resource cost table for each
# public contract entry point (issue #1588).
#
# Measurement source: `stellar contract invoke --sim-only`, which runs the
# invocation against the network's simulation budget and reports CPU
# instructions, memory bytes and read/write bytes without submitting a
# transaction. Requires the Stellar CLI and a configured network/source.
#
# Usage:
#   scripts/generate-performance-docs.sh [CONTRACT_ID]
#
# Environment:
#   CONTRACT_ID   Contract to measure (arg overrides this).
#   NETWORK       Stellar network to simulate against (default: testnet).
#   SOURCE        Source account for simulation (default: default identity).
#   OUTPUT        Output markdown path (default: docs/performance.md).
#
set -euo pipefail

CONTRACT_ID="${1:-${CONTRACT_ID:-}}"
NETWORK="${NETWORK:-testnet}"
SOURCE="${SOURCE:-}"
OUTPUT="${OUTPUT:-docs/performance.md}"

if [[ -z "$CONTRACT_ID" ]]; then
  echo "error: CONTRACT_ID is required (pass as arg or set CONTRACT_ID)" >&2
  exit 1
fi

if ! command -v stellar >/dev/null 2>&1; then
  echo "error: stellar CLI not found in PATH" >&2
  exit 1
fi

# Public entry points to measure. Keep in sync with the contract's #[contractimpl].
ENTRY_POINTS=(
  "initialize"
  "deposit"
  "withdraw"
  "transfer"
  "balance"
)

# Extract a numeric field from the simulation output. The CLI prints a
# human-readable summary; we grep the labelled value and keep the digits.
extract_metric() {
  local output="$1"
  local label="$2"
  printf '%s\n' "$output" \
    | grep -i "$label" \
    | head -n1 \
    | grep -oE '[0-9]+' \
    | head -n1 \
    || true
}

mkdir -p "$(dirname "$OUTPUT")"

{
  echo "# Contract Performance"
  echo
  echo "Resource costs for public contract entry points, measured with"
  echo "\`stellar contract invoke --sim-only\` against \`$NETWORK\`."
  echo
  echo "> This file is generated by \`scripts/generate-performance-docs.sh\`."
  echo "> Do not edit by hand; re-run the script to refresh the numbers."
  echo
  echo "| Entry point | CPU instructions | Memory (bytes) | Read bytes | Write bytes |"
  echo "| --- | ---: | ---: | ---: | ---: |"

  for fn in "${ENTRY_POINTS[@]}"; do
    args=(contract invoke --id "$CONTRACT_ID" --network "$NETWORK" --sim-only -- "$fn")
    if [[ -n "$SOURCE" ]]; then
      args+=(--source "$SOURCE")
    fi

    if ! sim_output="$(stellar "${args[@]}" 2>&1)"; then
      echo "| \`$fn\` | n/a | n/a | n/a | n/a |"
      echo "warning: simulation failed for $fn" >&2
      continue
    fi

    cpu="$(extract_metric "$sim_output" 'cpu')"
    mem="$(extract_metric "$sim_output" 'mem')"
    read_bytes="$(extract_metric "$sim_output" 'read')"
    write_bytes="$(extract_metric "$sim_output" 'write')"

    echo "| \`$fn\` | ${cpu:-n/a} | ${mem:-n/a} | ${read_bytes:-n/a} | ${write_bytes:-n/a} |"
  done
} > "$OUTPUT"

echo "wrote $OUTPUT"
